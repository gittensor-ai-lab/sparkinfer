void test_property(const Case& c, GrammarEngine& engine, const Vocab& vocab) {
    ChatRequest request;
    std::string err;
    CHECK(parse_chat_request_json(c.body, request, err));
    if (!err.empty()) {
        std::fprintf(stderr, "%s: request rejected: %s\n", c.name.c_str(), err.c_str());
        return;
    }
    ToolCallGrammar grammar;
    if (!build_tool_call_grammar(request, c.thinking, grammar, err)) {
        std::fprintf(stderr, "%s: no grammar: %s\n", c.name.c_str(), err.c_str());
        ++g_failures;
        return;
    }
    {
        std::string compile_err;
        bool exact = grammar.exact;
        if (!engine.make_constraint(grammar.structural_tag, exact, compile_err)) {
            std::fprintf(stderr, "%s: grammar does not compile: %s\n", c.name.c_str(), compile_err.c_str());
            ++g_failures;
            return;
        }
        if (!exact && grammar.exact) {
            grammar.exact = false;
            grammar.approximation = "a JSON value's string class could not be narrowed";
        }
    }
    std::mt19937 rng(12345);
    int finished = 0, accepted = 0, with_calls = 0, refused = 0;
    std::map<std::string, int> reasons;
    std::map<std::string, std::string> exact_reason_sample;   // full reason (with names) -> one output
    const bool demand = request.tool_choice == ToolChoiceMode::kRequired || request.tool_choice == ToolChoiceMode::kNamed;
    for (int i = 0; i < 400; ++i) {
        std::string text;
        if (!walk(engine, grammar.structural_tag, vocab, rng, text)) continue;
        ++finished;
        CHECK(utf8_lossy(text) == text);   // the UTF-8 mask keeps output valid
        const ParsedToolOutput out = parse_qwen36_tool_output(text, c.thinking, request);
        if (!out.error.empty()) {
            std::string reason = out.error;
            for (const char* p : {"parameter ", "function "}) {   // group by kind, not by name
                size_t at = reason.find(p);
                if (at != std::string::npos) {
                    size_t end = reason.find(' ', at + std::char_traits<char>::length(p));
                    reason.replace(at, (end == std::string::npos ? reason.size() : end) - at, std::string(p) + "X");
                }
            }
            ++reasons[reason];
            if (!exact_reason_sample.count(out.error)) exact_reason_sample[out.error] = utf8_lossy(text);
            if (++refused <= 3)
                std::fprintf(stderr, "%s%s: grammar output refused by the parser: %s\n---\n%s\n---\n",
                             c.name.c_str(), grammar.exact ? "" : " (approximate grammar)",
                             out.error.c_str(), utf8_lossy(text).substr(0, 1200).c_str());
            if (grammar.exact) ++g_failures;
            continue;
        }
        ++accepted;
        if (!out.tool_calls.empty()) ++with_calls;
        if (demand) CHECK(!out.tool_calls.empty());
        if (!request.parallel_tool_calls) CHECK(out.tool_calls.size() <= 1);
        if (request.tool_choice == ToolChoiceMode::kNamed)
            for (const auto& call : out.tool_calls) CHECK(call.name == request.required_tool_name);
    }
    std::printf("  %-32s exact=%d finished %3d/400, parsed %3d, refused %3d, with calls %3d%s%s\n",
                c.name.c_str(), grammar.exact, finished, accepted, refused, with_calls,
                grammar.exact ? "" : " -- ", grammar.approximation.c_str());
    for (const auto& [reason, count] : reasons) std::printf("      %4d x %s\n", count, reason.c_str());
    if (std::getenv("TOOL_GRAMMAR_SAMPLES")) {
        for (const auto& [reason, sample] : exact_reason_sample) {
            // Show the offending parameter when the reason names one.
            size_t at = std::string::npos;
            size_t name_at = reason.find("parameter ");
            if (name_at != std::string::npos) {
                const std::string name = reason.substr(name_at + 10, reason.find(' ', name_at + 10) - name_at - 10);
                at = sample.find("<parameter=" + name + ">");
            }
            if (at == std::string::npos) at = sample.find("<tool_call>");
            if (at == std::string::npos) at = 0;
            std::printf("    SAMPLE [%s]\n%s\n    END\n", reason.c_str(), sample.substr(at, 500).c_str());
        }
    }
    // Coverage, not correctness: a corpus the walks cannot finish proves nothing.
    CHECK(finished >= 40);
    if (demand) CHECK(with_calls >= 40);
}

// Hand-written outputs the grammar must refuse, and ones it must admit.
void test_boundaries(GrammarEngine& engine, const Vocab& vocab) {
    ChatRequest request;
    std::string err;
    CHECK(parse_chat_request_json(corpus()[4].body, request, err));   // named get_time, thinking off
    ToolCallGrammar grammar;
    CHECK(build_tool_call_grammar(request, false, grammar, err));
    const std::string& tag = grammar.structural_tag;
    const std::string call = "<tool_call>\n<function=get_time>\n<parameter=offset>\n2\n</parameter>\n<parameter=tz>\nUTC\n</parameter>\n</function>\n</tool_call>";
    CHECK(admits(engine, tag, vocab, call));
    CHECK(!admits(engine, tag, vocab, ""));                                             // named demands a call
    CHECK(!admits(engine, tag, vocab, "Sure." + call));                                 // no prose around it
    CHECK(!admits(engine, tag, vocab, "<tool_call>\n<function=get_weather>\n<parameter=city>\nParis\n</parameter>\n</function>\n</tool_call>"));
    CHECK(!admits(engine, tag, vocab, "<tool_call>\n<function=get_time>\n<parameter=tz>\nCET\n</parameter>\n</function>\n</tool_call>"));   // enum
    CHECK(!admits(engine, tag, vocab, "<tool_call>\n<function=get_time>\n<parameter=offset>\n20\n</parameter>\n<parameter=tz>\nUTC\n</parameter>\n</function>\n</tool_call>"));   // maximum
    CHECK(!admits(engine, tag, vocab, "<tool_call>\n<function=get_time>\n</function>\n</tool_call>"));   // tz is required
    CHECK(admits(engine, tag, vocab, call + "\n" + call));                              // parallel_tool_calls defaults to true
    CHECK(!admits(engine, tag, vocab, call + " bye"));                                  // nothing after the calls
    CHECK(!admits(engine, tag, vocab, "<tool_call>\n<function=get_time>\n<parameter=tz>\nUTC\n</parameter>x\n</parameter>\n</function>\n</tool_call>"));
    CHECK(!admits(engine, tag, vocab, "<tool_call>\n<function=get_time>\n<parameter=offset>\n\xe6\x97\n</parameter>\n<parameter=tz>\nUTC\n</parameter>\n</function>\n</tool_call>"));   // broken UTF-8

    // A JSON-typed argument keeps '<' -- only '<' that starts protocol markup is refused.
    ChatRequest rule_request;
    CHECK(parse_chat_request_json(R"({"messages":[{"role":"user","content":"go"}],"tool_choice":"required","tools":[{"type":"function","function":{"name":"save_rule","parameters":{"type":"object","properties":{"rule":{"type":"object","properties":{"expr":{"type":"string"}},"required":["expr"]}},"required":["rule"]}}}]})",
                                  rule_request, err));
    ToolCallGrammar rule_grammar;
    CHECK(build_tool_call_grammar(rule_request, false, rule_grammar, err));
    auto rule_call = [](const std::string& expr) {
        return "<tool_call>\n<function=save_rule>\n<parameter=rule>\n{\"expr\": \"" + expr + "\"}\n</parameter>\n</function>\n</tool_call>";
    };
    CHECK(admits(engine, rule_grammar.structural_tag, vocab, rule_call("x < 10 and y <= 3")));
    CHECK(admits(engine, rule_grammar.structural_tag, vocab, rule_call("<b>bold</b> <<to")));
    CHECK(!admits(engine, rule_grammar.structural_tag, vocab, rule_call("call <tool_call> now")));
    CHECK(!admits(engine, rule_grammar.structural_tag, vocab, rule_call("a</parameter>b")));
    CHECK(!admits(engine, rule_grammar.structural_tag, vocab, rule_call("<|im_end|>")));
    CHECK(admits(engine, rule_grammar.structural_tag, vocab, rule_call("\\u003ctool is escaped")));

    // response_format with thinking on: a JSON string may hold '<', never a think marker.
    ChatRequest format_request;
    CHECK(parse_chat_request_json(R"({"messages":[{"role":"user","content":"go"}],"response_format":{"type":"json_schema","json_schema":{"name":"o","schema":{"type":"object","properties":{"html":{"type":"string"}},"required":["html"]}}}})",
                                  format_request, err));
    ToolCallGrammar format_grammar;
    CHECK(build_response_format_grammar(format_request, true, format_grammar, err));
    CHECK(format_grammar.exact);
    CHECK(admits(engine, format_grammar.structural_tag, vocab, "ok\n</think>\n\n{\"html\": \"<b>x</b> <think\"}"));
    CHECK(!admits(engine, format_grammar.structural_tag, vocab, "ok\n</think>\n\n{\"html\": \"a</think>b\"}"));
    CHECK(!admits(engine, format_grammar.structural_tag, vocab, "ok\n</think>\n\n{\"html\": 1e400}"));
}


