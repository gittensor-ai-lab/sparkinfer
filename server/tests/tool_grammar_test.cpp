int g_failures = 0;

#define CHECK(expr)                                                                            \
    do {                                                                                       \
        if (!(expr)) {                                                                         \
            std::fprintf(stderr, "FAIL: %s:%d: %s\n", __FILE__, __LINE__, #expr);             \
            ++g_failures;                                                                      \
        }                                                                                      \
    } while (0)

// What the server's detokenizer does to generated bytes (HF ByteLevel decoding is UTF-8 lossy): each
// maximal invalid subsequence becomes U+FFFD. A byte-level vocabulary can emit a lone continuation
// byte; the parser never sees it raw, so neither may this test.
std::string utf8_lossy(const std::string& in) {
    static const std::string kReplacement = "\xef\xbf\xbd";
    std::string out;
    size_t i = 0;
    const size_t n = in.size();
    auto byte = [&](size_t k) { return static_cast<unsigned char>(in[k]); };
    while (i < n) {
        const unsigned char c = byte(i);
        if (c < 0x80) { out.push_back(static_cast<char>(c)); ++i; continue; }
        int len = 0;
        unsigned char lo = 0x80, hi = 0xBF;
        if (c >= 0xC2 && c <= 0xDF) len = 2;
        else if (c == 0xE0) { len = 3; lo = 0xA0; }
        else if ((c >= 0xE1 && c <= 0xEC) || c == 0xEE || c == 0xEF) len = 3;
        else if (c == 0xED) { len = 3; hi = 0x9F; }
        else if (c == 0xF0) { len = 4; lo = 0x90; }
        else if (c >= 0xF1 && c <= 0xF3) len = 4;
        else if (c == 0xF4) { len = 4; hi = 0x8F; }
        if (len == 0) { out += kReplacement; ++i; continue; }
        size_t k = 1;
        for (; k < static_cast<size_t>(len) && i + k < n; ++k) {
            const unsigned char b = byte(i + k);
            if (k == 1 ? (b < lo || b > hi) : (b < 0x80 || b > 0xBF)) break;
        }
        if (k == static_cast<size_t>(len)) out.append(in, i, len);
        else out += kReplacement;
        i += k;
    }
    return out;
}

struct Vocab {
    std::vector<std::string> tokens;
    int stop = -1;
};

Vocab make_vocab(const std::set<std::string>& words) {
    Vocab v;
    for (int b = 1; b < 256; ++b) v.tokens.push_back(std::string(1, static_cast<char>(b)));
    std::set<std::string> extra = {
        "<tool_call>", "</tool_call>", "<think>", "</think>", "</think>\n\n", "<function=", "</function>",
        "<parameter=", "</parameter>", "\n</parameter>\n", ">\n", "\n", "\n\n", "<tool", "<tools>",
        "<|im_start|>", "<|im_", "</tool_response>", "true", "false", "null", "{\"", "\": ", "\"", ", ",
        "0", "12", "-3", "2.5", "1e3", "[", "]", "{", "}", "Paris", "hello world", "\xc3\xa9", "\xe6\x97\xa5",
        "\\n", "\\\"", "   "};
    extra.insert(words.begin(), words.end());
    for (const std::string& s : extra)
        if (s.size() > 1) v.tokens.push_back(s);
    v.tokens.push_back("<|im_end|>");
    v.stop = static_cast<int>(v.tokens.size()) - 1;
    return v;
}

// One walk through the production constraint (grammar mask AND UTF-8 mask). True when it reached a
// stop within the step budget; `text` is the output without the stop token. A step with no allowed
// token is a grammar dead end and fails.
bool walk(GrammarEngine& engine, const std::string& tag, const Vocab& vocab, std::mt19937& rng, std::string& text) {
    bool exact = true;
    std::string err;
    auto constraint = engine.make_constraint(tag, exact, err);
    if (!constraint) {
        std::fprintf(stderr, "no constraint: %s\n", err.c_str());
        ++g_failures;
        return false;
    }
    const int vocab_size = static_cast<int>(vocab.tokens.size());
    std::vector<uint32_t> bits((vocab_size + 31) / 32);
    text.clear();
    for (int step = 0; step < 900; ++step) {
        constraint->fill_next_mask(bits.data(), vocab_size);
        std::vector<int> allowed, multi;
        for (int id = 0; id < vocab_size; ++id) {
            if (!((bits[id / 32] >> (id % 32)) & 1)) continue;
            allowed.push_back(id);
            if (id != vocab.stop && vocab.tokens[id].size() > 1) multi.push_back(id);
        }
        if (allowed.empty()) {
            std::fprintf(stderr, "dead end after %zu bytes: %s\n", text.size(), text.c_str());
            ++g_failures;
            return false;
        }
        const bool can_stop = (bits[vocab.stop / 32] >> (vocab.stop % 32)) & 1;
        int pick;
        if (can_stop && (rng() % 4 == 0 || step > 600)) pick = vocab.stop;
        else if (!multi.empty() && (rng() % 3 != 0 || step > 450)) pick = multi[rng() % multi.size()];
        else pick = allowed[rng() % allowed.size()];
        if (!constraint->accept(pick)) {
            std::fprintf(stderr, "constraint refused a token its own mask allowed\n");
            ++g_failures;
            return false;
        }
        if (pick == vocab.stop) return true;
        text += vocab.tokens[pick];
    }
    return false;
}

// Feeds `text` byte by byte through a fresh constraint, then a stop. The vocabulary holds every byte.
bool admits(GrammarEngine& engine, const std::string& tag, const Vocab& vocab, const std::string& text) {
    bool exact = true;
    std::string err;
    auto constraint = engine.make_constraint(tag, exact, err);
    if (!constraint) return false;
    const int vocab_size = static_cast<int>(vocab.tokens.size());
    std::vector<uint32_t> bits((vocab_size + 31) / 32);
    auto step = [&](int id) {
        constraint->fill_next_mask(bits.data(), vocab_size);
        return ((bits[id / 32] >> (id % 32)) & 1) && constraint->accept(id);
    };
    for (unsigned char c : text)
        if (c == 0 || !step(static_cast<int>(c) - 1)) return false;   // byte b is token b - 1
    return step(vocab.stop);
}

